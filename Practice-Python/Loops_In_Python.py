# Loops in Python
# Loops are used to perform repeating works(repeat instructions)
# While Loop:-
count = 1

while count <= 5:
    print(count)
    count += 1

count = 1
while count <= 5:
    print("Hello World!")
    count += 1

i = 1
while i <= 5:
    print(i)
    i += 1

i = 5
while i > 0:
    print(i)
    i -= 1
print("Loop Ended")
